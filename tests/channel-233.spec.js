import { test, expect } from '@playwright/test'
async function setup(page, other = false) {
  page.on('dialog', dialog => dialog.accept())
  await page.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname
    if (!path.startsWith('/api/')) return route.continue()
    if (path === '/api/contract-terms/channel-rule-recommendation') return route.fulfill({ json: { lines: [], matched_lines: 0, partner_rule_status: 'none', message: '无关联合同' } })
    return route.abort()
  })
  await page.goto('/tests/fixtures/channel-233.html' + (other ? '?other=1' : ''))
  await expect(page.getByTestId('current')).toContainText('合成游戏')
}
test('233 explicit opt-in saves negative platform amount, reopens unknown, and restores local draft', async ({ page }) => {
  await setup(page)
  await page.getByRole('button', { name: '启用233资料未齐暂存' }).click()
  await expect(page.locator('.channel-line-items-table tbody td').nth(11)).toHaveText('待补')
  await expect(page.getByTestId('current')).toContainText('"validationStatus":"incomplete"')
  await page.getByRole('button', { name: '测试保存本机草稿', exact: true }).click()
  await page.reload()
  await expect(page.getByTestId('current')).toContainText('"platformSettlementAmount":-5.34')
  await expect(page.locator('.channel-line-items-table tbody td').nth(11)).toHaveText('待补')
  await page.getByRole('button', { name: '测试保存', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('')
  await expect(page.getByTestId('saved')).toContainText('"settlement_rule_code":"channel_233_incomplete"')
  await page.getByRole('button', { name: '测试重新打开', exact: true }).click()
  await expect(page.getByRole('button', { name: '补齐资料并转正常规则' })).toBeVisible()
  await expect(page.getByTestId('current')).toContainText('"settlementAmount":-5.34')
  await page.getByRole('button', { name: '测试确认', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('资料未齐')
})
test('233 completion requires actual data and allows only its manual operands', async ({ page }) => {
  await setup(page)
  await page.getByRole('button', { name: '启用233资料未齐暂存' }).click()
  await page.getByRole('button', { name: '测试保存', exact: true }).click()
  await expect(page.getByTestId('saved')).toContainText('channel_233_incomplete')
  await page.getByRole('button', { name: '测试重新打开', exact: true }).click()
  await page.getByRole('button', { name: '补齐资料并转正常规则' }).click()
  await page.getByRole('button', { name: '测试保存', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('资料的来源')
  await expect(page.locator('.channel-contract-rule-status')).not.toContainText('正在')
  await page.getByLabel('补齐资料来源说明').fill('合成原始充值明细与分成依据')
  await page.getByRole('combobox', { name: '规则模板', exact: true }).selectOption('share_only')
  const row = page.locator('.channel-line-items-table tbody tr').first()
  await row.locator('td').nth(2).locator('input').fill('100')
  await row.locator('td').nth(11).locator('input').click()
  await row.locator('td').nth(11).locator('input').fill('50')
  await row.locator('td').nth(12).locator('input').fill('0')
  await row.locator('td').nth(7).locator('input').fill('0')
  await row.locator('td').nth(17).locator('input').fill('50')
  await page.getByRole('button', { name: '测试保存', exact: true }).click()
  await expect(page.getByRole('alert')).not.toContainText('正在')
  await expect(page.getByTestId('saved')).toContainText('"complete_incomplete_draft":true')
  await expect(page.getByTestId('saved')).toContainText('"status":"pending"')
})
test('other channels retain contract validation and never expose incomplete opt-in', async ({ page }) => {
  await setup(page, true)
  await expect(page.getByRole('button', { name: '启用233资料未齐暂存' })).toHaveCount(0)
  await page.getByRole('button', { name: '测试保存', exact: true }).click()
  await expect(page.getByTestId('saved')).toHaveText('null')
  await expect(page.getByRole('alert')).toContainText('分成比例')
})
